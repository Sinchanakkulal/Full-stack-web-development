public class java_math{
    public static void main(String[] args){
        System.out.println("max: "+ Math.max(2,3));  //3
        System.out.println("Min: "+Math.min(2,3));  //2
        System.out.println("Square root: "+ Math.sqrt(25)); //5 
        System.out.println("absolute value of -5: "+Math.abs(-5)); //5
        System.out.println("value of 8 raised to the power of 2: "+Math.pow(8,2));
        System.out.println("rounds to the nearest integer: "+Math.round(4.6));
        System.out.println(Math.ceil(5.2));  //6
        System.out.println(Math.floor(5.2));    //5

        
    }
}